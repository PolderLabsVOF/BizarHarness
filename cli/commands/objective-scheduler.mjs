/**
 * cli/commands/objective-scheduler.mjs
 *
 * F-194 + production-autonomy audit Milestone 2 ("Resumable controller"):
 * durable ObjectiveRun scheduler with leases and orphan recovery.
 *
 * This complements `cli/task-ledger.mjs`. task-ledger coordinates
 * cross-worktree **task** state under git's common directory. This module
 * owns **objective** state — the higher-level aggregate that spans tasks,
 * evidence, and learner outcomes — and persists it under the operator-only
 * `BIZAR_HOME/state/` subtree (mode 0o700).
 *
 * Why a separate store:
 *   - Objectives outlive any single Claude session. A crashed session
 *     must be picked up by the next session without losing the goal,
 *     the attempt counter, or the lease history.
 *   - task-ledger is git-coordinated; objectives are operator-audited and
 *     must not be writable from a worktree. The 0o700 boundary enforces
 *     that.
 *   - Phase semantics differ. An objective is `planning → executing →
 *     verifying → done | failed | cancelled`; tasks have a wider state
 *     machine that does not match.
 *
 * Invariants:
 *   - `objective_run_id` is the UUID generated by `createObjectiveRun`
 *     from `@polderlabs/bizar-sdk`. This module does not generate ids.
 *   - A lease is meaningful only while `status='active'` and the phase
 *     is non-terminal. Terminal objectives always have
 *     `lease_expires_at = NULL`.
 *   - `recoverStale()` is idempotent: each orphan is released exactly
 *     once per recovery sweep and its `attempt` is incremented exactly
 *     once. Calling it twice without intervening work is a no-op.
 *   - Every state change records a row in `objective_events` so a
 *     reader can replay the run without consulting the evidence ledger.
 */

import { chmodSync, mkdirSync, statSync } from 'node:fs';
import { dirname, isAbsolute, join, resolve } from 'node:path';
import { homedir } from 'node:os';

const Database = (await import('better-sqlite3')).default;

/** Lifecycle phases — must match `ObjectiveRunPhase` in the SDK. */
export const OBJECTIVE_PHASES = Object.freeze([
  'planning',
  'executing',
  'verifying',
  'done',
  'failed',
  'cancelled',
]);

/** Status — must match `ObjectiveRunStatus` in the SDK. */
export const OBJECTIVE_STATUSES = Object.freeze([
  'active',
  'succeeded',
  'failed',
  'cancelled',
]);

/** Phases that own an active lease. */
export const ACTIVE_PHASES = new Set(['planning', 'executing', 'verifying']);
/** Statuses that own an active lease. */
export const ACTIVE_STATUSES = new Set(['active']);

const DEFAULT_LEASE_MS = 30 * 60 * 1_000; // 30 minutes
const MIN_LEASE_MS = 1_000;
const MAX_LEASE_MS = 24 * 60 * 60 * 1_000;
const PHASE_CHECK = new Set(OBJECTIVE_PHASES);
const STATUS_CHECK = new Set(OBJECTIVE_STATUSES);

const SCHEMA_SQL = `
PRAGMA journal_mode = WAL;
PRAGMA synchronous = NORMAL;
PRAGMA foreign_keys = ON;
PRAGMA busy_timeout = 2000;

CREATE TABLE IF NOT EXISTS objectives (
  objective_run_id  TEXT PRIMARY KEY,
  owner             TEXT,
  phase             TEXT NOT NULL
                    CHECK (phase IN ('planning','executing','verifying','done','failed','cancelled')),
  status            TEXT NOT NULL
                    CHECK (status IN ('active','succeeded','failed','cancelled')),
  goal              TEXT NOT NULL,
  payload_json      TEXT NOT NULL DEFAULT '{}',
  attempt           INTEGER NOT NULL DEFAULT 0,
  lease_expires_at  INTEGER,
  heartbeat_at      INTEGER,
  blocker           TEXT,
  created_at        INTEGER NOT NULL,
  updated_at        INTEGER NOT NULL,
  terminal_at       INTEGER
);

CREATE TABLE IF NOT EXISTS objective_events (
  id                INTEGER PRIMARY KEY AUTOINCREMENT,
  objective_run_id  TEXT NOT NULL REFERENCES objectives(objective_run_id) ON DELETE CASCADE,
  kind              TEXT NOT NULL,
  ts                INTEGER NOT NULL,
  payload_json      TEXT NOT NULL DEFAULT '{}'
);

CREATE INDEX IF NOT EXISTS idx_objectives_phase_status
  ON objectives (phase, status);
CREATE INDEX IF NOT EXISTS idx_objectives_lease
  ON objectives (lease_expires_at);
CREATE INDEX IF NOT EXISTS idx_objective_events_run_ts
  ON objective_events (objective_run_id, ts);
`;

export class ObjectiveSchedulerError extends Error {
  constructor(code, message, details = {}) {
    super(message);
    this.name = 'ObjectiveSchedulerError';
    this.code = code;
    this.details = details;
  }
}

function parseJson(value, fallback) {
  try {
    return JSON.parse(value);
  } catch {
    return fallback;
  }
}

function requireText(value, field) {
  const normalized = String(value ?? '').trim();
  if (!normalized) {
    throw new ObjectiveSchedulerError('INVALID_INPUT', `${field} must be a non-empty string`);
  }
  return normalized;
}

function requireOneOf(value, field, allowed) {
  if (!allowed.has(value)) {
    throw new ObjectiveSchedulerError(
      'INVALID_INPUT',
      `${field} must be one of ${[...allowed].join(', ')} (got ${JSON.stringify(value)})`,
    );
  }
  return value;
}

function normalizeLeaseMs(value) {
  const parsed = Number(value ?? DEFAULT_LEASE_MS);
  if (!Number.isFinite(parsed)) return DEFAULT_LEASE_MS;
  return Math.max(MIN_LEASE_MS, Math.min(MAX_LEASE_MS, Math.floor(parsed)));
}

/**
 * Default DB path. Stored under `BIZAR_HOME/state/objectives.sqlite` with
 * 0o700 so only the operator can read or write it. `cwd`/`env` mirror the
 * `BIZAR_HOME` precedence used elsewhere in the harness (override > env >
 * XDG > ~/.config/bizar).
 */
export function resolveObjectiveSchedulerDb({ cwd = process.cwd(), env = process.env, override } = {}) {
  if (override) {
    return isAbsolute(override) ? override : resolve(cwd, override);
  }
  if (env?.BIZAR_OBJECTIVE_DB) {
    const v = env.BIZAR_OBJECTIVE_DB;
    return isAbsolute(v) ? v : resolve(cwd, v);
  }
  const home =
    env?.BIZAR_HOME
    || (env?.XDG_CONFIG_HOME ? `${env.XDG_CONFIG_HOME}/bizar` : null)
    || (env?.HOME ? `${env.HOME}/.config/bizar` : null)
    || join(homedir(), '.config', 'bizar');
  return join(home, 'state', 'objectives.sqlite');
}

/**
 * Open (or initialize) the durable objective scheduler at `dbPath`.
 * Pass `dbPath: ':memory:'` for tests; the schema and lifecycle
 * semantics are identical to the on-disk database.
 */
export class ObjectiveScheduler {
  constructor(options = {}) {
    this.dbPath = options.dbPath ?? resolveObjectiveSchedulerDb({ cwd: options.cwd, env: options.env });
    this.now = options.now || (() => Date.now());
    if (this.dbPath !== ':memory:') {
      mkdirSync(dirname(this.dbPath), { recursive: true, mode: 0o700 });
      try {
        // Tighten in case the directory pre-existed with a looser mode.
        const cur = statSync(dirname(this.dbPath)).mode & 0o777;
        if (cur !== 0o700) chmodSync(dirname(this.dbPath), 0o700);
      } catch { /* non-fatal on Windows */ }
    }
    /** @type {import('better-sqlite3').Database} */
    this.db = new Database(this.dbPath);
    this.db.exec(SCHEMA_SQL);
    this.db.pragma('journal_mode = WAL');
    this.db.pragma('synchronous = NORMAL');
    this.db.pragma('foreign_keys = ON');
    this.db.pragma('busy_timeout = 2000');
  }

  close() {
    this.db.close();
  }

  _row(objectiveRunId) {
    return this.db.prepare(`SELECT * FROM objectives WHERE objective_run_id = ?`).get(objectiveRunId);
  }

  _event(objectiveRunId, kind, payload = {}, now = this.now()) {
    this.db.prepare(
      `INSERT INTO objective_events (objective_run_id, kind, ts, payload_json)
       VALUES (?, ?, ?, ?)`,
    ).run(objectiveRunId, kind, now, JSON.stringify(payload ?? {}));
  }

  _serialize(row) {
    if (!row) return null;
    return {
      objectiveRunId: row.objective_run_id,
      phase: row.phase,
      status: row.status,
      goal: row.goal,
      owner: row.owner,
      attempt: row.attempt,
      leaseExpiresAt: row.lease_expires_at,
      heartbeatAt: row.heartbeat_at,
      blocker: row.blocker,
      payload: parseJson(row.payload_json, {}),
      createdAt: row.created_at,
      updatedAt: row.updated_at,
      terminalAt: row.terminal_at,
    };
  }

  /**
   * Insert a new objective row in `planning` / `active`. The caller
   * supplies the canonical `objectiveRunId` (from `createObjectiveRun` in
   * the SDK) and the full `goal` + `payload` so a future replay can
   * reconstruct the run without consulting the SDK.
   */
  createObjective({ objectiveRunId, goal, payload = {} } = {}) {
    const id = requireText(objectiveRunId, 'objectiveRunId');
    const g = requireText(goal, 'goal');
    const now = this.now();
    const row = this._row(id);
    if (row) {
      throw new ObjectiveSchedulerError(
        'OBJECTIVE_EXISTS',
        `objective already exists: ${id}`,
        { objectiveRunId: id },
      );
    }
    const tx = this.db.transaction(() => {
      this.db.prepare(
        `INSERT INTO objectives
           (objective_run_id, owner, phase, status, goal, payload_json,
            attempt, lease_expires_at, heartbeat_at, blocker,
            created_at, updated_at, terminal_at)
         VALUES (?, NULL, 'planning', 'active', ?, ?, 0, NULL, NULL, NULL, ?, ?, NULL)`,
      ).run(id, g, JSON.stringify(payload ?? {}), now, now);
      this._event(id, 'created', { goal: g, phase: 'planning', status: 'active' }, now);
    });
    tx.immediate();
    return this._serialize(this._row(id));
  }

  getObjective({ objectiveRunId }) {
    const id = requireText(objectiveRunId, 'objectiveRunId');
    return this._serialize(this._row(id));
  }

  listObjectives({ phase, status } = {}) {
    let rows;
    if (phase && status) {
      rows = this.db.prepare(
        `SELECT * FROM objectives WHERE phase = ? AND status = ? ORDER BY created_at, objective_run_id`,
      ).all(phase, status);
    } else if (phase) {
      rows = this.db.prepare(
        `SELECT * FROM objectives WHERE phase = ? ORDER BY created_at, objective_run_id`,
      ).all(phase);
    } else if (status) {
      rows = this.db.prepare(
        `SELECT * FROM objectives WHERE status = ? ORDER BY created_at, objective_run_id`,
      ).all(status);
    } else {
      rows = this.db.prepare(
        `SELECT * FROM objectives ORDER BY created_at, objective_run_id`,
      ).all();
    }
    return rows.map((row) => this._serialize(row));
  }

  /**
   * Claim an objective for `owner`. A claim succeeds when:
   *   - The objective exists.
   *   - It is non-terminal (`status='active'`, phase in
   *     `{planning, executing, verifying}`).
   *   - Either it has no live lease, or the existing lease is held by
   *     the same owner (renewal), or the existing lease is expired.
   *
   * On success the lease is set to `now + leaseMs` and `attempt` is
   * incremented exactly once per first-time claim.
   */
  claimObjective({ objectiveRunId, owner, leaseMs } = {}) {
    const id = requireText(objectiveRunId, 'objectiveRunId');
    const ownerId = requireText(owner, 'owner');
    const now = this.now();
    const lease = normalizeLeaseMs(leaseMs);

    const tx = this.db.transaction(() => {
      const row = this._row(id);
      if (!row) {
        throw new ObjectiveSchedulerError(
          'OBJECTIVE_NOT_FOUND',
          `objective not found: ${id}`,
          { objectiveRunId: id },
        );
      }
      if (!ACTIVE_STATUSES.has(row.status) || !ACTIVE_PHASES.has(row.phase)) {
        throw new ObjectiveSchedulerError(
          'OBJECTIVE_NOT_CLAIMABLE',
          `objective ${id} is ${row.phase}/${row.status} and cannot be claimed`,
          { phase: row.phase, status: row.status },
        );
      }
      const leaseLive = row.lease_expires_at && row.lease_expires_at > now;
      if (leaseLive && row.owner && row.owner !== ownerId) {
        throw new ObjectiveSchedulerError(
          'LEASE_HELD',
          `objective ${id} is held by ${row.owner} until ${row.lease_expires_at}`,
          { owner: row.owner, leaseExpiresAt: row.lease_expires_at },
        );
      }
      const incrementAttempt = !leaseLive || !row.owner;
      this.db.prepare(
        `UPDATE objectives
           SET owner = ?,
               lease_expires_at = ?,
               heartbeat_at = ?,
               attempt = attempt + ?,
               updated_at = ?
         WHERE objective_run_id = ?`,
      ).run(ownerId, now + lease, now, incrementAttempt ? 1 : 0, now, id);
      this._event(id, 'claimed', {
        owner: ownerId,
        leaseExpiresAt: now + lease,
        previousOwner: row.owner ?? null,
        attemptBefore: row.attempt,
        attemptAfter: row.attempt + (incrementAttempt ? 1 : 0),
      }, now);
    });
    tx.immediate();
    return this._serialize(this._row(id));
  }

  /**
   * Renew the lease for an objective already held by `owner`. The owner
   * MUST match — a heartbeat from a non-owner is rejected so a stale
   * worker cannot keep a recovered objective's lease alive.
   */
  heartbeatObjective({ objectiveRunId, owner, leaseMs } = {}) {
    const id = requireText(objectiveRunId, 'objectiveRunId');
    const ownerId = requireText(owner, 'owner');
    const now = this.now();
    const lease = normalizeLeaseMs(leaseMs);

    const tx = this.db.transaction(() => {
      const row = this._row(id);
      if (!row) {
        throw new ObjectiveSchedulerError(
          'OBJECTIVE_NOT_FOUND',
          `objective not found: ${id}`,
          { objectiveRunId: id },
        );
      }
      if (row.owner !== ownerId) {
        throw new ObjectiveSchedulerError(
          'OWNER_MISMATCH',
          `objective ${id} is owned by ${row.owner ?? '<none>'}, not ${ownerId}`,
          { owner: row.owner, expectedOwner: ownerId },
        );
      }
      if (!ACTIVE_PHASES.has(row.phase) || !ACTIVE_STATUSES.has(row.status)) {
        throw new ObjectiveSchedulerError(
          'OBJECTIVE_NOT_ACTIVE',
          `objective ${id} is ${row.phase}/${row.status} and not eligible for heartbeat`,
          { phase: row.phase, status: row.status },
        );
      }
      this.db.prepare(
        `UPDATE objectives
           SET lease_expires_at = ?,
               heartbeat_at = ?,
               updated_at = ?
         WHERE objective_run_id = ?`,
      ).run(now + lease, now, now, id);
      this._event(id, 'heartbeat', {
        owner: ownerId,
        leaseExpiresAt: now + lease,
      }, now);
    });
    tx.immediate();
    return this._serialize(this._row(id));
  }

  /**
   * Move an objective from `expectedFromPhase` to `toPhase` (and
   * optionally to `toStatus`). The transition is rejected if the
   * objective is not currently in `expectedFromPhase` or the owner
   * does not match — preventing two workers from racing each other
   * into the verifying phase.
   *
   * When `toPhase` is terminal (`done` | `failed` | `cancelled`), the
   * lease is cleared and `terminal_at` is stamped.
   */
  transitionObjective({
    objectiveRunId,
    owner,
    expectedFromPhase,
    toPhase,
    toStatus,
    reason,
    payload,
  } = {}) {
    const id = requireText(objectiveRunId, 'objectiveRunId');
    const ownerId = requireText(owner, 'owner');
    const fromPhase = requireOneOf(expectedFromPhase, 'expectedFromPhase', PHASE_CHECK);
    const nextPhase = requireOneOf(toPhase, 'toPhase', PHASE_CHECK);
    const now = this.now();

    const tx = this.db.transaction(() => {
      const row = this._row(id);
      if (!row) {
        throw new ObjectiveSchedulerError(
          'OBJECTIVE_NOT_FOUND',
          `objective not found: ${id}`,
          { objectiveRunId: id },
        );
      }
      if (row.owner !== ownerId) {
        throw new ObjectiveSchedulerError(
          'OWNER_MISMATCH',
          `objective ${id} is owned by ${row.owner ?? '<none>'}, not ${ownerId}`,
          { owner: row.owner, expectedOwner: ownerId },
        );
      }
      if (row.phase !== fromPhase) {
        throw new ObjectiveSchedulerError(
          'PHASE_MISMATCH',
          `objective ${id} is in ${row.phase}, not ${fromPhase}`,
          { actualPhase: row.phase, expectedPhase: fromPhase },
        );
      }
      const nextStatus = toStatus
        ? requireOneOf(toStatus, 'toStatus', STATUS_CHECK)
        : (nextPhase === 'done'
            ? 'succeeded'
            : nextPhase === 'failed' || nextPhase === 'cancelled'
              ? nextPhase
              : 'active');
      const isTerminal = nextPhase === 'done' || nextPhase === 'failed' || nextPhase === 'cancelled';
      this.db.prepare(
        `UPDATE objectives
           SET phase = ?,
               status = ?,
               lease_expires_at = ?,
               heartbeat_at = ?,
               blocker = ?,
               terminal_at = ?,
               updated_at = ?
         WHERE objective_run_id = ?`,
      ).run(
        nextPhase,
        nextStatus,
        isTerminal ? null : row.lease_expires_at,
        now,
        reason ?? null,
        isTerminal ? now : null,
        now,
        id,
      );
      this._event(id, 'transitioned', {
        owner: ownerId,
        fromPhase,
        toPhase: nextPhase,
        fromStatus: row.status,
        toStatus: nextStatus,
        reason: reason ?? null,
        payload: payload ?? null,
      }, now);
    });
    tx.immediate();
    return this._serialize(this._row(id));
  }

  /**
   * Cancel an objective regardless of its current phase. The owner MUST
   * match unless `force: true` is passed (reserved for the operator CLI).
   */
  cancelObjective({ objectiveRunId, owner, reason, force = false } = {}) {
    const id = requireText(objectiveRunId, 'objectiveRunId');
    const now = this.now();
    const tx = this.db.transaction(() => {
      const row = this._row(id);
      if (!row) {
        throw new ObjectiveSchedulerError(
          'OBJECTIVE_NOT_FOUND',
          `objective not found: ${id}`,
          { objectiveRunId: id },
        );
      }
      if (!force && row.owner && row.owner !== owner) {
        throw new ObjectiveSchedulerError(
          'OWNER_MISMATCH',
          `objective ${id} is owned by ${row.owner}, not ${owner}`,
          { owner: row.owner, expectedOwner: owner },
        );
      }
      this.db.prepare(
        `UPDATE objectives
           SET phase = 'cancelled',
               status = 'cancelled',
               lease_expires_at = NULL,
               heartbeat_at = ?,
               blocker = ?,
               terminal_at = ?,
               updated_at = ?
         WHERE objective_run_id = ?`,
      ).run(now, reason ?? null, now, now, id);
      this._event(id, 'cancelled', {
        owner: row.owner,
        reason: reason ?? null,
        forced: !!force,
      }, now);
    });
    tx.immediate();
    return this._serialize(this._row(id));
  }

  /**
   * Sweep every objective whose lease has expired and whose phase is
   * still active. Each orphan is:
   *   1. Released (owner cleared, lease_expires_at = NULL).
   *   2. Attempt-counter incremented.
   *   3. Emitted as a `lease-expired` event with the previous owner +
   *      the new attempt number so a downstream claimer can audit the
   *      recovery.
   *
   * Returns the list of recovered objectives so callers can re-queue
   * them with `claimObjective`. The sweep is idempotent — calling it
   * twice without intervening work is a no-op.
   */
  recoverStale({ thresholdMs = 0, now = this.now() } = {}) {
    const cutoff = now - Math.max(0, Number(thresholdMs) || 0);
    const recovered = [];
    const tx = this.db.transaction(() => {
      const orphans = this.db.prepare(
        `SELECT * FROM objectives
          WHERE status = 'active'
            AND phase IN ('planning','executing','verifying')
            AND lease_expires_at IS NOT NULL
            AND lease_expires_at <= ?`,
      ).all(cutoff);
      for (const row of orphans) {
        this.db.prepare(
          `UPDATE objectives
             SET owner = NULL,
                 lease_expires_at = NULL,
                 attempt = attempt + 1,
                 heartbeat_at = ?,
                 updated_at = ?
           WHERE objective_run_id = ?`,
        ).run(now, now, row.objective_run_id);
        this._event(row.objective_run_id, 'lease-expired', {
          previousOwner: row.owner,
          previousLeaseExpiresAt: row.lease_expires_at,
          attemptAfter: row.attempt + 1,
        }, now);
        recovered.push(this._serialize(this._row(row.objective_run_id)));
      }
    });
    tx.immediate();
    return { recovered, scannedAt: now, cutoff };
  }

  /**
   * Return the lifecycle event log for one objective, oldest first.
   * Useful for `bizar explain-run` (audit fix #79) and for tests.
   */
  listEvents({ objectiveRunId } = {}) {
    const id = requireText(objectiveRunId, 'objectiveRunId');
    const rows = this.db.prepare(
      `SELECT id, kind, ts, payload_json
         FROM objective_events
        WHERE objective_run_id = ?
        ORDER BY ts, id`,
    ).all(id);
    return rows.map((row) => ({
      id: row.id,
      kind: row.kind,
      ts: row.ts,
      payload: parseJson(row.payload_json, {}),
    }));
  }
}
